"""Study U2 arms: generic, hand-designed exploration baselines for TechTree (public information only).

Agents hold only the public facade (``env.agent_interface``); this module is under the same source
check as ``explorers`` and ``layered`` (no reflective builtins, dunder, frame or traceback
attributes, no private attributes of objects other than ``self``; imports restricted).

Shared part
-----------
Every baseline is an ``explorers.Explorer`` with its search step replaced, so it keeps the
engine's memory and evidence per world (exact discoveries, candidate preconditions, failure
clauses, which key announced which slot), its replay planner and its gating (before searching, it
holds the known concepts the engine would hold: the parents of the lowest open level and the keys
of the slots in use) and replays the goal once it is known. Arms differ only in what they press
when they search. Every action goes through ``Episode.step``, so every press, including the presses
that reach a search node and every press of a macro, is charged. All per-world state below
persists across the episodes of a world and is dropped with it, as the engine's memory is.

The *context* of a search is the held set at that moment. Within an episode it only grows; a
firing therefore ends the current search and a search in the new context begins (a later episode
resumes a context's search when the engine's gating leads back to the same held set). The
*actions* of a context are the primitives available in it (announced: base symbols and active
slots; silent: every symbol, as the environment lists them), with no prior over slots.

``iw``, ``iw1``, ``iw2``: width-based novelty search (Lipovetzky and Geffner 2012)
------------------------------------------------------------------------------
States are (held set, last L presses since the last clear), L the public maximal sequence length
(``trace_atoms``). The atoms of a state are the values of the environment's state variables that
the agent observes or reconstructs: each held concept, each available slot (announced), the
progress flag (signal on) and ``(j, s)`` for the symbol s at position j = 1..L from the end of the
trace. Each held context has one search tree, rooted at the state in which the search first found
itself in that context: the empty trace for the first context of an episode, otherwise the trace
that reached the context (the subgoal state, as in serialized IW, SIW, of the same paper). A node is
the root's trace followed by a path of actions, its state the last L presses of that sequence.
Held concepts and slots are constant within a tree (a firing moves the search to another tree), so
only the trace and progress atoms can be new, and novelty is computed over those (equivalently).

Breadth-first search (FIFO) generates the children of a node in a successor order drawn at random
per pass. A generated node is novel when it makes some tuple of at most w atoms true for the first
time in the pass; only novel nodes are expanded. Every generated node is executed, so the goal test
happens at generation: a k-press composite fires when a node whose last k presses spell it is
generated, which needs only its parent to be novel. From an empty root one pass of IW(w) therefore
tests every sequence of up to w + 1 presses. ``iw1`` and ``iw2`` keep w = 1 or 2; when a pass ends
without a firing, a new pass starts with an empty novelty table and a new random successor order
(randomized restarts). ``iw`` is iterated width, the paper's complete method: a context starts at
w = 1 and each pass that ends without a firing raises w by one, up to the number of varying atoms,
where novelty means an unvisited state and a pass visits every state reachable from the root;
further passes repeat that width in new random orders.

There is no simulator to restore states, so a node is generated by executing it from the current
state along the shortest path the public trace semantics allow: a node whose sequence is shorter
than L needs the exact trace since a clear (``wait`` and its sequence, or the rest of it when the
current trace is a prefix of it); a longer one is reached by the shortest suffix of its last L
symbols that completes the current trace (in silent mode only presses made under the current held
set are reused, since an earlier slot press may have been inert). Every press on the way is charged
and tests windows like any other press. An interrupted node (a firing, the end of an episode) goes
back to the front of its queue.

``macro_uniform``, ``macro_sys``: flat macro expansion
------------------------------------------------------
The unfiltered limit of macro-operators (docs/PRIOR_ART.md C14 filters learned macros; here none is
filtered): every sequence of 1..B actions of the context (B = ``macro_bound``, by default L) is one
macro action; executing a macro presses its symbols in order without clearing the trace (as an
atomic action would), and a firing interrupts it like any chunk. ``macro_uniform`` draws a macro
uniformly from the expanded action set at every search decision (no memory of tried macros). A
uniform draw picks a length in proportion to its number of sequences and then a uniform sequence of
that length, so the presses form an i.i.d. uniform stream over the context's actions, exactly as
uniformly random primitives do: listing every sequence as an action gives a blind sampler nothing.
``macro_sys`` executes every macro of its context once per pass, shortest first and in a random
order within each length (the action-space blow-up: all shorter macros come first, and the number
of macros grows as the number of actions to the power B); an interrupted macro is put back; when
the pass is exhausted a new pass starts with new random orders.

``archive``: archive-based exploration in the spirit of Go-Explore
-----------------------------------------------------------------
Cells are held sets. The archive of a world records every cell the agent has been in and how often
it was selected. At its first search decision of an episode the agent selects the most promising
cell: the one with the most held concepts (in TechTree holding a concept never prevents another one
from firing), ties by fewest selections; it returns there by replaying known sequences with the
shared planner and then explores with uniformly random available primitives until the episode ends
(new cells found on the way are added). It does not read the signal. In the U setting its cell is
the held set the engine's gating reaches, so it is the same algorithm as ``macro_uniform`` there.

The factory also builds the comparison arms of studies U and L (``pooled``, ``remember``,
``promote``, ...) and the anchors (``random``, ``oracle``, ``oracle_library``) unchanged, so one study
config can run them side by side. ``ROW_SUMMARIES`` declares the analysis summary of the counters
that baseline rows carry.
"""

from __future__ import annotations

from collections import Counter, deque

import numpy as np

from .explorers import Chunk, Explorer, make_explorer
from .layered import make_layered

DEFAULT_PARAMS = {"trace_atoms": "max_length", "macro_bound": "max_length"}


def _bound(spec, value) -> int:
    return max(spec.level_lengths) if value == "max_length" else int(value)


def check_params(params: dict | None) -> dict:
    p = {**DEFAULT_PARAMS, **(params or {})}
    extra = set(p) - set(DEFAULT_PARAMS)
    if extra:
        raise KeyError(f"unknown study U2 agent parameters {sorted(extra)}")
    for name, v in p.items():
        if v != "max_length" and not (isinstance(v, int) and not isinstance(v, bool) and v >= 1):
            raise ValueError(f"agent parameter {name} must be 'max_length' or a positive integer")
    return p


def decode(actions: tuple, length: int, index: int) -> tuple[int, ...]:
    """The ``index``-th sequence of ``length`` actions in lexicographic order of ``actions``."""
    base, out = len(actions), []
    for _ in range(length):
        index, r = divmod(index, base)
        out.append(actions[r])
    return tuple(reversed(out))


def subsets(items: list, size: int):
    """Every combination of ``size`` items, in the order of ``items``."""
    if size == 0:
        yield ()
        return
    for i in range(len(items) - size + 1):
        for rest in subsets(items[i + 1:], size - 1):
            yield (items[i],) + rest


class Baseline(Explorer):
    """Engine with the search step replaced (see the module docstring). The engine's constructor
    draws the per-world preference seed first (common random numbers across arms); ``configure``
    then sets the arm's parameters and per-world state."""

    KEYS: tuple[str, ...] = ()
    TAG = "baseline"

    def configure(self, params: dict | None = None):
        self.params = check_params(params)
        self.per_world: dict[str, dict] = {}
        self.pending = None
        self.counts: Counter = Counter()
        return self

    def run_episode(self, env, token, meter) -> dict:
        self.counts = Counter()
        row = super().run_episode(env, token, meter)
        row.update({f"{self.TAG}_{key}": int(self.counts[key]) for key in self.KEYS})
        return row

    def world_state(self, ep) -> dict:
        return self.per_world.setdefault(ep.spec.world_key, {})

    def context_actions(self, ep) -> tuple[int, ...]:
        return tuple(s for s in range(ep.spec.n_symbols) if ep.obs.available[s])

    def reusable(self, k, ep, n: int) -> bool:
        """Whether the last ``n`` presses still stand for the environment's trace: in silent mode
        a slot press made under another held set may have been inert."""
        if not k.silent or n <= 0:
            return True
        tr, ctx = ep.trace, ep.trace_ctx
        return all(tr[i] < k.P or ctx[i] == ep.held for i in range(len(tr) - n, len(tr)))


# ------------------------------------------------------------------------------- IW(k)
class Tree:
    """IW search state of one held context, rooted at the state where the context was entered."""

    def __init__(self, actions: tuple[int, ...], root: tuple[int, ...], root_progress, width: int):
        self.actions = actions
        self.root = root
        self.root_progress = root_progress
        self.width = width
        self.order: tuple[int, ...] = ()
        self.queue: deque = deque()
        self.table: set = set()
        self.passes = 0
        self.generated = 0
        self.novel = 0


class IW(Baseline):
    """IW(WIDTH) with randomized restarts; ``WIDTH = 0`` is iterated width."""

    KEYS = ("passes", "generated", "novel", "pruned", "width")
    TAG = "iw"
    WIDTH = 1

    # ------------------------------------------------------------- states and atoms
    def span(self, ep) -> int:
        """Trace positions that are atoms: at most the trace the episode keeps."""
        return min(_bound(ep.spec, self.params["trace_atoms"]), max(ep.spec.level_lengths))

    @staticmethod
    def node_state(sequence: tuple, span: int) -> tuple:
        return sequence[-span:] if len(sequence) >= span else sequence

    def current_state(self, ep, span: int) -> tuple:
        tr = ep.trace
        return tuple(tr[-span:]) if len(tr) >= span else tuple(tr)

    def atoms(self, ep, trace, progress) -> list:
        """The atoms that can vary within a tree (held concepts and slots are constant there)."""
        out = [("p", progress)] if ep.spec.signal else []
        return out + [("t", j, int(trace[-j])) for j in range(1, len(trace) + 1)]

    def tuples(self, atoms: list, width: int) -> list:
        return [t for size in range(1, min(width, len(atoms)) + 1) for t in subsets(atoms, size)]

    def max_width(self, ep) -> int:
        return self.span(ep) + (1 if ep.spec.signal else 0)

    # --------------------------------------------------------------------- search
    def trees(self, ep) -> dict:
        return self.world_state(ep).setdefault("trees", {})

    def new_pass(self, tree: Tree, ep):
        if tree.passes and not self.WIDTH:
            tree.width = min(tree.width + 1, self.max_width(ep))  # iterated width
        tree.passes += 1
        self.counts["passes"] += 1
        root = self.atoms(ep, self.node_state(tree.root, self.span(ep)), tree.root_progress)
        tree.table = set(self.tuples(root, tree.width))
        tree.order = tuple(int(a) for a in self.rng.permutation(np.array(tree.actions)))
        tree.queue = deque((a,) for a in tree.order)

    def evaluate(self, tree: Tree, node: tuple, ep):
        """Novelty test of a generated node in the state just reached."""
        span = self.span(ep)
        tuples = self.tuples(self.atoms(ep, self.current_state(ep, span), ep.obs.progress), tree.width)
        new = [t for t in tuples if t not in tree.table]
        tree.generated += 1
        self.counts["generated"] += 1
        if new:
            tree.table.update(new)
            tree.novel += 1
            self.counts["novel"] += 1
            tree.queue.extend(node + (a,) for a in tree.order)
        else:
            self.counts["pruned"] += 1

    def settle(self, ep):
        """Evaluate the node issued last if its execution completed in this context."""
        if self.pending is None:
            return
        pep, steps, ctx, node, tree = self.pending
        self.pending = None
        if pep is ep and ep.steps == steps and ep.held == ctx:
            self.evaluate(tree, node, ep)
        else:
            tree.queue.appendleft(node)

    def route(self, k, ep, state: tuple, span: int) -> tuple[int, ...]:
        """Shortest press sequence that makes the agent's state equal ``state``."""
        tr = ep.trace
        if len(state) >= span:
            for j in range(min(span - 1, len(tr)), 0, -1):
                if tuple(tr[-j:]) == state[:j] and self.reusable(k, ep, j):
                    return state[j:]
            return state
        n = len(tr)
        if n < span and tuple(tr) == state[:n] and self.reusable(k, ep, n):
            return state[n:]
        return (ep.spec.wait_action,) + state

    def _search(self, k, ep, level) -> Chunk:
        self.settle(ep)
        trees, span = self.trees(ep), self.span(ep)
        tree = trees.get(ep.held)
        if tree is None:  # the context is entered here: its tree is rooted at the current state
            tree = trees[ep.held] = Tree(self.context_actions(ep), self.current_state(ep, span),
                                         ep.obs.progress, self.WIDTH or 1)
        while True:
            if not tree.queue:
                self.new_pass(tree, ep)
                if not tree.queue:
                    return Chunk("idle", (ep.spec.wait_action,))
            self.counts["width"] = max(self.counts["width"], tree.width)
            node = tree.queue.popleft()
            state = self.node_state(tree.root + node, span)
            if self.current_state(ep, span) == state and self.reusable(k, ep, len(state)):
                self.evaluate(tree, node, ep)  # already in the node's state
                continue
            presses = self.route(k, ep, state, span)
            self.pending = (ep, ep.steps + len(presses), ep.held, node, tree)
            return Chunk("search_primitive", presses)


class IW1(IW):
    WIDTH = 1


class IW2(IW):
    WIDTH = 2


class IteratedWidth(IW):
    WIDTH = 0


# -------------------------------------------------------------------- flat macro expansion
class MacroUniform(Baseline):
    KEYS = ("macros",)
    TAG = "macro"

    def macro_count(self, n_actions: int, bound: int) -> list[int]:
        return [n_actions ** length for length in range(1, bound + 1)]

    def _search(self, k, ep, level) -> Chunk:
        actions = self.context_actions(ep)
        sizes = self.macro_count(len(actions), _bound(ep.spec, self.params["macro_bound"]))
        r = int(self.rng.integers(sum(sizes)))
        length = 1
        while r >= sizes[length - 1]:
            r -= sizes[length - 1]
            length += 1
        self.counts["macros"] += 1
        return Chunk("search_macro", decode(actions, length, r))


class MacroSystematic(Baseline):
    KEYS = ("passes", "macros")
    TAG = "macro"

    def queues(self, ep) -> dict:
        return self.world_state(ep).setdefault("queues", {})

    def new_pass(self, ep) -> deque:
        self.counts["passes"] += 1
        actions = self.context_actions(ep)
        bound = _bound(ep.spec, self.params["macro_bound"])
        return deque(decode(actions, length, int(i)) for length in range(1, bound + 1)
                     for i in self.rng.permutation(len(actions) ** length))

    def _search(self, k, ep, level) -> Chunk:
        if self.pending is not None:
            pep, steps, ctx, macro, queue = self.pending
            self.pending = None
            if not (pep is ep and ep.steps == steps and ep.held == ctx):
                queue.appendleft(macro)  # interrupted: not executed in full
        queues = self.queues(ep)
        queue = queues.get(ep.held)
        if not queue:
            queue = queues[ep.held] = self.new_pass(ep)
        macro = queue.popleft()
        self.pending = (ep, ep.steps + len(macro), ep.held, macro, queue)
        self.counts["macros"] += 1
        return Chunk("search_macro", macro)


# ------------------------------------------------------------------------------ archive
class Archive(Baseline):
    KEYS = ("selected", "cells", "cell_size", "explore")
    TAG = "archive"

    def _search(self, k, ep, level) -> Chunk:
        st = self.world_state(ep)
        cells = st.setdefault("cells", {})
        cells.setdefault(ep.held, 0)
        if st.get("episode") is not ep:  # first search decision of this episode: select a cell
            st["episode"] = ep
            best = max(cells, key=lambda h: (len(h), -cells[h], tuple(sorted(h))))
            cells[best] += 1
            st["target"] = best
            self.counts["selected"] = 1
            self.counts["cell_size"] = len(best)
        self.counts["cells"] = len(cells)
        missing = [c for c in sorted(st["target"]) if c not in ep.held and c in k.known]
        if missing:
            return self._replay(k, ep, k.plan(missing, ep.held)[0])
        self.counts["explore"] += 1
        return Chunk("search_primitive", (int(self.rng.choice(np.array(self.context_actions(ep)))),))


# ------------------------------------------------------------------------- row summaries
COUNTER_PREFIXES = ("iw_", "macro_", "archive_")
ENGINE_KEYS = ("macro_steps",)  # an engine row key that shares a prefix


def counter_summary(rows: list[dict]) -> dict:
    """Per variant/arm: totals of the counters baseline rows carry (IW passes and nodes, the
    largest IW width, macros and macro passes, archive selections and exploring presses). The
    archive's selected cell size is averaged over the episodes in which a cell was selected; an
    episode that only replays the known goal selects none."""
    groups: dict[str, list] = {}
    for r in rows:
        if any(key.startswith(COUNTER_PREFIXES) and key not in ENGINE_KEYS for key in r):
            groups.setdefault(f"{r['variant']}/{r['arm']}", []).append(r)
    out = {}
    for cell, rs in sorted(groups.items()):
        keys = sorted({key for r in rs for key in r if key.startswith(COUNTER_PREFIXES)} - set(ENGINE_KEYS))
        s: dict = {"episodes": len(rs)}
        for key in keys:
            vals = [r[key] for r in rs if key in r]
            if key == "iw_width":
                s["iw_width_max"] = max(vals)
            elif key == "archive_cells":
                s["archive_cells_max"] = max(vals)
            elif key == "archive_cell_size":
                sel = [r[key] for r in rs if r.get("archive_selected")]
                s["archive_cell_size_mean_selected"] = float(np.mean(sel)) if sel else None
            else:
                s[key] = int(sum(vals))
        out[cell] = s
    return out


ROW_SUMMARIES = {"baseline_counters": counter_summary}


# ------------------------------------------------------------------------------ factory
BASELINES = {"iw": IteratedWidth, "iw1": IW1, "iw2": IW2, "macro_uniform": MacroUniform,
             "macro_sys": MacroSystematic, "archive": Archive}
U_ARMS = ("pooled", "isolated", "nomem", "blind", "oracle", "random")
L_ARMS = ("none", "remember", "promote", "sham_promote", "adaptive", "oracle_library")


def make_baseline(name: str, rng: np.random.Generator, params: dict | None = None):
    """Study U2 arms; the comparison arms and anchors of studies U and L are built unchanged."""
    p = check_params(params)
    if name in BASELINES:
        return BASELINES[name](rng).configure(p)
    if name in U_ARMS:
        return make_explorer(name, rng)
    if name in L_ARMS:
        return make_layered(name, rng)
    raise KeyError(f"unknown study U2 arm {name!r}")
